/// 解析 CSS 属性名，返回与之匹配的强类型 Struct 名称或错误
pub fn resolve_property_type(prop: &str, span: Span) -> Result<PropertyResolveResult> {
    // 1. 自定义 CSS 变量 (--*) 统一映射为 props::Any
    if prop.starts_with("--") {
        return Ok(PropertyResolveResult::CustomVar);
    }

    // 2. 短别名优先 PHF 查表
    if let Some(&type_name) = SHORT_ALIAS_MAP.get(prop) {
        return Ok(PropertyResolveResult::Builtin(type_name));
    }

    // 3. 将 kebab-case 转换为 PascalCase 并查询标准 PHF 属性哈希表
    let mut pascal = String::with_capacity(prop.len());
    for part in prop.split('-') {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            pascal.extend(first.to_uppercase());
            pascal.push_str(chars.as_str());
        }
    }

    if let Some(&type_name) = STANDARD_PASCAL_MAP.get(pascal.as_str()) {
        return Ok(PropertyResolveResult::Builtin(type_name));
    }

    // 4. 既不是 CSS 变量，也不是合法标准 CSS 属性，直接返回明确的过程宏编译报错
    Err(syn::Error::new(
        span,
        format!(
            "未知的 CSS 属性 '{}'。如果是自定义 CSS 变量，请使用 '--{}' 格式；请检查拼写。",
            prop, prop
        ),
    ))
}
