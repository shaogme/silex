/// 属性解析结果
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PropertyResolveResult {
    /// 匹配到强类型的标准属性/短别名 (如 Padding, BorderRadius)
    Builtin(&'static str),
    /// 自定义 CSS 变量 (--*)，统一映射为 props::Any
    CustomVar,
}

